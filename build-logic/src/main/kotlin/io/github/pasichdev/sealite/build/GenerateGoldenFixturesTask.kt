package io.github.pasichdev.sealite.build

import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.util.Base64

/**
 * Embeds the golden `*.db` fixtures as Kotlin `ByteArray` constants (Base64 chunks decoded at class
 * initialisation) into a generated test source. No resources are involved, so the same tests run
 * on Kotlin/Native, where there is no classpath to read from.
 */
@CacheableTask
abstract class GenerateGoldenFixturesTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val fixtures: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun run() {
        val dir = outputDir.get().asFile.resolve("io/github/pasichdev/sealite")
        dir.mkdirs()
        val out = StringBuilder()
        out.append(
            """
            // Generated by GenerateGoldenFixturesTask from testdata/*.db. Do not edit.
            @file:OptIn(kotlin.io.encoding.ExperimentalEncodingApi::class)

            package io.github.pasichdev.sealite

            import kotlin.io.encoding.Base64

            private fun decode(vararg chunks: String): ByteArray = Base64.decode(chunks.joinToString(""))

            """.trimIndent(),
        )
        out.append('\n')
        for (file in fixtures.files.sortedBy { it.name }) {
            val name = file.nameWithoutExtension.uppercase()
            val base64 = Base64.getEncoder().encodeToString(file.readBytes())
            out.append("\n/** `${file.name}`, ${file.length()} bytes. */\n")
            out.append("internal val GOLDEN_$name: ByteArray = decode(\n")
            // Short lines: a class-file string constant is limited to 65535 bytes, and diffs stay readable.
            for (chunk in base64.chunked(CHUNK)) out.append("    \"").append(chunk).append("\",\n")
            out.append(")\n")
        }
        dir.resolve("GoldenFixtures.kt").writeText(out.toString())
    }

    private companion object {
        const val CHUNK = 96
    }
}
